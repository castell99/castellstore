-- ── 5. Funciones ───────────────────────────────────────────────

-- Página de garantía: el cliente ve su aceptación con el token del enlace.
create or replace function public.aceptacion_por_token(p_token text)
returns table(cliente text, equipo text, imei text, condicion text,
              fecha_venta text, total numeric, version_txt text,
              aceptado_en timestamptz, firma text, nombre_conf text)
language sql security definer set search_path to 'public'
as $$
  select a.cliente, a.equipo, a.imei, a.condicion,
         a.fecha_venta, a.total, a.version_txt,
         a.aceptado_en, a.firma, a.nombre_conf
  from aceptaciones a where a.token = p_token;
$$;

-- Página de garantía: el cliente firma una sola vez.
create or replace function public.registrar_aceptacion(p_token text, p_firma text, p_nombre text)
returns boolean
language plpgsql security definer set search_path to 'public'
as $$
declare filas int;
begin
  update aceptaciones
     set aceptado_en = now(), firma = p_firma, nombre_conf = p_nombre
   where token = p_token and aceptado_en is null;
  get diagnostics filas = row_count;
  return filas > 0;
end;
$$;

-- Al entregar un equipo se borran las claves de desbloqueo.
create or replace function public.limpiar_bloqueo_al_entregar()
returns trigger
language plpgsql
as $$
begin
  if new.estado = 'Entregado' then
    new.clave_bloqueo  := null;
    new.patron_bloqueo := null;
    new.tipo_bloqueo   := null;
  end if;
  return new;
end $$;

create trigger trg_limpiar_bloqueo
  before insert or update on public.tecnicos
  for each row execute function public.limpiar_bloqueo_al_entregar();

grant execute on function public.aceptacion_por_token(text)              to anon, authenticated;
grant execute on function public.registrar_aceptacion(text, text, text)  to anon, authenticated;


-- ── 6. Storage: buckets y permisos ─────────────────────────────
-- equipos-imagenes es público (fotos del catálogo).
-- contratos-docs y servicios-fotos son privados: solo con sesión,
-- y se ven con URLs firmadas temporales.
insert into storage.buckets (id, name, public) values
  ('equipos-imagenes', 'equipos-imagenes', true),
  ('contratos-docs',   'contratos-docs',   false),
  ('servicios-fotos',  'servicios-fotos',  false)
on conflict (id) do nothing;

create policy cs_anon_lee_catalogo on storage.objects
  for select to anon
  using (bucket_id = 'equipos-imagenes');

create policy cs_auth_storage on storage.objects
  for all to authenticated
  using      (bucket_id = any (array['contratos-docs', 'servicios-fotos', 'equipos-imagenes']))
  with check (bucket_id = any (array['contratos-docs', 'servicios-fotos', 'equipos-imagenes']));


