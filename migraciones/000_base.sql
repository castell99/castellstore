-- ── 3. Vista pública del catálogo ──────────────────────────────
-- Solo productos con stock y sin precio de proveedor. Funciona con
-- permisos del dueño, por eso el visitante anónimo puede leerla
-- aunque productos tenga RLS. Se le quita todo menos SELECT.
create view public.productos_publicos as
  select id, nombre, categoria, precio, stock, emoji, variantes,
         imagen1, imagen2, marca
  from public.productos
  where stock > 0;

revoke all on public.productos_publicos from anon, authenticated;
grant select on public.productos_publicos to anon, authenticated;

-- El anónimo no necesita ningún permiso directo sobre productos:
-- lee el catálogo solo a través de la vista. (Igual que en Castell Tech.)
revoke all on public.productos from anon;


